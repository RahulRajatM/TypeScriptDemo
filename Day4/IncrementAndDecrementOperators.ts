//increament ++
//decreament --
let x = 5;
console.log(x); // Output: 5

x++; // Incrementing x by 1
console.log(x); // Output: 6

x--; // Decrementing x by 1
console.log(x); // Output: 5

// You can also use the increment and decrement operators in expressions:
let y = 10;
console.log(y); // Output: 10

let z = y++ + 5; // z is assigned the value of y (10) and then y is incremented
console.log(z); // Output: 15
console.log(y); // Output: 11

let w = --y + 3; // y is decremented first (10) and then w is assigned the value of y + 3
console.log(w); // Output: 13
console.log(y); // Output: 10       
