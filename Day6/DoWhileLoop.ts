// do while loop is a control flow statement that executes a block of code at least once and then repeatedly executes the block as long as a specified condition is true. The syntax for a do while loop in TypeScript is as follows:

/* do {
    // code to be executed
} while (condition); */

//Example:
/* let count: number = 0;

do {
    console.log(count); // Output: 0, 1, 2, 3, 4
    count++;
} while (count < 5);
 */
//In this example, the do while loop will execute the block of code at least once, even if the initial value of count is greater than or equal to 5. After the first execution, it will check the condition and continue to execute as long as count is less than 5.

